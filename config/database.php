use Illuminate\Support\Str;

/*
|--------------------------------------------------------------------------
| Parse DATABASE_URL if available (Railway, Heroku, etc.)
|--------------------------------------------------------------------------
*/

$databaseUrl = env('DATABASE_URL');

if ($databaseUrl && !env('DB_HOST')) {
    $parsed = parse_url($databaseUrl);
    if ($parsed) {
        $scheme = $parsed['scheme'] ?? '';
        $driverMap = [
            'mysql' => 'mysql',
            'mariadb' => 'mariadb',
            'postgres' => 'pgsql',
            'postgresql' => 'pgsql',
            'sqlite' => 'sqlite',
        ];
        $driver = $driverMap[$scheme] ?? $scheme;
        $host = $parsed['host'] ?? '127.0.0.1';
        if (str_contains($host, '://')) {
            $host = parse_url($host, PHP_URL_HOST) ?? $host;
        }
        $envOverrides = [
            'DB_CONNECTION' => $driver,
            'DB_HOST' => $host,
            'DB_PORT' => (string) ($parsed['port'] ?? ($driver === 'pgsql' ? 5432 : 3306)),
            'DB_DATABASE' => ltrim($parsed['path'] ?? '', '/'),
            'DB_USERNAME' => $parsed['user'] ?? '',
            'DB_PASSWORD' => $parsed['pass'] ?? '',
        ];
        foreach ($envOverrides as $key => $value) {
            if ($value !== '' && $value !== null) {
                putenv("$key=$value");
                $_ENV[$key] = $value;
                $_SERVER[$key] = $value;
            }
        }
    }
}

